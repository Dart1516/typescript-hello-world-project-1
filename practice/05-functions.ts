// Example 1: A function that returns a greeting.
function sayHello(name: string): string {
    return `Hello, ${name}!`;
}

console.log(sayHello("Maria"));

// Example 2: A function that returns a total.
function addNumbers(firstNumber: number, secondNumber: number): number {
    return firstNumber + secondNumber;
}

console.log(addNumbers(4, 6));
